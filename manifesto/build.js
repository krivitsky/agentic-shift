#!/usr/bin/env node
/**
 * Manifesto generator — zero dependencies, plain Node.
 *
 * Edit content in manifesto/content/*.json, then run:
 *   node manifesto/build.js
 *
 * Generates (never hand-edit these):
 *   public/index.html                      EN
 *   public/<lang>/index.html               each translation
 *   public/<lang>/agentic-shift-<lang>.md  downloadable Markdown, per language
 *   public/sitemap.xml
 *   the MANIFESTO-marked region of public/llms.txt (all languages)
 *   the MANIFESTO-marked region of README.md (English)
 *
 * Everything outside the MANIFESTO markers (llms.txt's summary/Meetups/Links,
 * the README's tech details) is hand-written and left alone.
 *
 * The canonical English pair shown under each translated pair is read from
 * en.json at build time — translations never restate it, so it cannot drift.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONTENT = path.join(__dirname, 'content');
const PUBLIC = path.join(ROOT, 'public');
const ORIGIN = 'https://agentic-shift.com';
const BANNER = '<!-- GENERATED by manifesto/build.js from manifesto/content/{lang}.json — do not edit by hand. -->';

// Order defines the language switcher order. `en` must come first: it is the
// canonical source for the English pairs and for llms.txt / README.
// A language appears on the site only once content/<lang>.json exists, so a
// translation in progress is simply absent rather than half-rendered.
const ALL_LANGS = ['en', 'de', 'nl', 'fr', 'it', 'es', 'pt', 'pl', 'cs', 'da', 'no', 'sv', 'uk', 'ru', 'zh', 'ja'];
const LANGS = ALL_LANGS.filter((l) => fs.existsSync(path.join(CONTENT, `${l}.json`)));

const missing = ALL_LANGS.filter((l) => !LANGS.includes(l));
if (!LANGS.includes('en')) throw new Error('content/en.json is required — it is the canonical source.');

const OG_LOCALE = {
  en: 'en_US', de: 'de_DE', nl: 'nl_NL', fr: 'fr_FR', it: 'it_IT',
  es: 'es_ES', pt: 'pt_PT', cs: 'cs_CZ', uk: 'uk_UA', ru: 'ru_RU',
  zh: 'zh_CN', ja: 'ja_JP', pl: 'pl_PL', da: 'da_DK', no: 'nb_NO', sv: 'sv_SE',
};

// Wording for the switcher's aria-label, per language.
const LANGBAR_LABEL = {
  en: 'Language', de: 'Sprache', nl: 'Taal', fr: 'Langue', it: 'Lingua',
  es: 'Idioma', pt: 'Idioma', cs: 'Jazyk', uk: 'Мова', ru: 'Язык',
  zh: '语言', ja: '言語', pl: 'Język', da: 'Sprog', no: 'Språk', sv: 'Språk',
};

const read = (p) => fs.readFileSync(p, 'utf8');
const load = (lang) => JSON.parse(read(path.join(CONTENT, `${lang}.json`)));

const all = Object.fromEntries(LANGS.map((l) => [l, load(l)]));
const en = all.en;

// What the renderers read: a translation layered over English, so a language
// that is mid-pass still ships a readable page instead of "undefined". The
// parity check below reads the raw JSON, names every gap and exits 1 — the
// fallback keeps you iterating, it does not let an incomplete language pass.
const view = (c) => ({
  ...en, ...c,
  meta: { ...en.meta, ...c.meta },
  hero: { ...en.hero, ...c.hero },
  foot: { ...en.foot, ...c.foot },
  ui: { ...en.ui, ...c.ui },
});
const template = read(path.join(__dirname, 'template.html'));

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const entities = (s) => s
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'");

// Convert the inline HTML used in content values to plain text or markdown,
// for the llms.txt / README manifesto blocks. `emphasis`: 'md' renders
// definition/strong as **bold** and amber/em as *italic*; 'none' strips them.
// `links`: 'md' → [text](url); 'paren' → text (url). A sentinel pass collapses
// nested bold/italic (e.g. a <strong> wrapping a definition span) into a single
// pair, so the markdown never emits broken **…**…** runs.
const B_OPEN = String.fromCharCode(0xE000);
const B_CLOSE = String.fromCharCode(0xE001);
const I_OPEN = String.fromCharCode(0xE002);
const I_CLOSE = String.fromCharCode(0xE003);
const S_OPEN = String.fromCharCode(0xE004);
const S_CLOSE = String.fromCharCode(0xE005);

function inline(html, { emphasis, links }) {
  let s = String(html);
  s = s.replace(/<a\b[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g,
    links === 'md' ? '[$2]($1)' : '$2 ($1)');
  s = s.replace(/<span class="definition">([\s\S]*?)<\/span>/g, B_OPEN + '$1' + B_CLOSE);
  s = s.replace(/<span class="amber">([\s\S]*?)<\/span>/g, I_OPEN + '$1' + I_CLOSE);
  s = s.replace(/<span class="strike">([\s\S]*?)<\/span>/g, S_OPEN + '$1' + S_CLOSE);
  s = s.replace(/<strong>/g, B_OPEN).replace(/<\/strong>/g, B_CLOSE);
  s = s.replace(/<em>/g, I_OPEN).replace(/<\/em>/g, I_CLOSE);
  s = s.replace(/<[^>]+>/g, '');           // drop any remaining tags (e.g. <span class="lite">)
  s = entities(s);

  let out = '';
  let bold = 0;
  let ital = 0;
  let strike = 0;
  const bMark = emphasis === 'md' ? '**' : '';
  const iMark = emphasis === 'md' ? '*' : '';
  const sMark = emphasis === 'md' ? '~~' : '';
  for (const ch of s) {
    if (ch === B_OPEN) { if (bold === 0) out += bMark; bold++; }
    else if (ch === B_CLOSE) { bold = Math.max(0, bold - 1); if (bold === 0) out += bMark; }
    else if (ch === I_OPEN) { if (ital === 0) out += iMark; ital++; }
    else if (ch === I_CLOSE) { ital = Math.max(0, ital - 1); if (ital === 0) out += iMark; }
    else if (ch === S_OPEN) { if (strike === 0) out += sMark; strike++; }
    else if (ch === S_CLOSE) { strike = Math.max(0, strike - 1); if (strike === 0) out += sMark; }
    else out += ch;
  }
  return out.replace(/\s+/g, ' ').trim();
}


function hreflang() {
  const rows = LANGS.map((l) =>
    `  <link rel="alternate" hreflang="${l}" href="${ORIGIN}${all[l].dir}">`);
  rows.push(`  <link rel="alternate" hreflang="x-default" href="${ORIGIN}${en.dir}">`);
  return rows.join('\n');
}

function langbar(current) {
  return LANGS.map((l) => {
    const c = all[l];
    const active = l === current ? ' aria-current="page"' : '';
    return `      <a href="${c.dir}" hreflang="${l}" lang="${l}"${active}>${esc(c.name)}</a>`;
  }).join('\n');
}

// One localized term with, on translated pages, its canonical English word
// beneath it — sourced from en.json, so the gloss can never drift. A
// translation carrying more shifts than en.json has nothing to gloss;
// parityDrift names that mismatch.
function term(c, i, key) {
  const word = esc(c.shifts[i][key]);
  if (c.lang === 'en' || !en.shifts[i]) return word;
  return `${word}<span class="gloss" lang="en">${esc(en.shifts[i][key])}</span>`;
}

// The shift rows: one slider per shift, "from" at the left end, "to" at the
// right end, the note beside it. No numbers: the shifts are a set, not a
// sequence — which ones an organization takes on, and how far, is its call.
function rows(c) {
  return c.shifts.map((s, i) => `          <li class="row">
            <div class="row-main">
              <div class="ends">
                <div class="from">${term(c, i, 'from')}</div>
                <div class="to">${term(c, i, 'to')}</div>
              </div>
              <div class="fader" data-i="${i}">
                <div class="ticks t1"></div><div class="ticks t2"></div>
                <div class="track"></div><div class="bar"></div>
                <input class="hit" type="range" min="0" max="100" step="1" value="0" aria-label="${esc(`${s.from} → ${s.to}`)}">
                <div class="cap"></div>
              </div>
            </div>
            <p class="note">${s.note}</p>
          </li>`).join('\n');
}

function render(c) {
  const p = (list) => list.map((x) => `          <p>${x}</p>`).join('\n');
  const map = {
    LANG: c.lang,
    DIR: c.dir,
    OG_LOCALE: OG_LOCALE[c.lang],
    LANGBAR_LABEL: esc(LANGBAR_LABEL[c.lang]),
    LANGBAR: langbar(c.lang),
    HREFLANG: hreflang(),
    META_TITLE: esc(c.meta.title),
    META_DESCRIPTION: esc(c.meta.description),
    META_KEYWORDS: esc(c.meta.keywords),
    META_OG_TITLE: esc(c.meta.ogTitle),
    META_OG_DESCRIPTION: esc(c.meta.ogDescription),
    META_SCHEMA_DESCRIPTION: esc(c.meta.schemaDescription),
    META_LLMS_TITLE: esc(c.meta.llmsTitle),
    HEADLINE_LEAD: esc(c.hero.headlineLead),
    HEADLINE_TAIL: esc(c.hero.headlineTail),
    SUBTITLE: esc(c.hero.subtitle),
    SHIFT_HEAD: c.shiftHead,
    SHIFT_INTRO: p(c.shiftIntro),
    OWN_HEAD: esc(c.ownHead),
    ROWS: rows(c),
    USE_HEAD: c.useHead,
    USE: p(c.use),
    QA_HEAD: c.qaHead,
    QA: c.qa.map((x) => `          <p class="q">${esc(x.q)}</p>\n          <p>${x.a}</p>`).join('\n'),
    FOOT_BY: esc(c.foot.by),
    UI_DOWNLOAD: esc(c.ui.download),
    UI_THEME_LIGHT: esc(c.ui.themeToLight),
    UI_THEME_DARK: esc(c.ui.themeToDark),
    MD_HREF: `${c.dir}agentic-shift-${c.lang}.md`,
    MD_DOWNLOAD: `agentic-shift-${c.lang}.md`,
    MD_LANG: c.lang.toUpperCase(),
  };
  let out = template;
  for (const [k, v] of Object.entries(map)) out = out.split(`{{${k}}}`).join(v);
  const left = out.match(/\{\{[A-Z_]+\}\}/g);
  if (left) throw new Error(`${c.lang}: unreplaced placeholders: ${[...new Set(left)].join(', ')}`);
  return out.replace('<!DOCTYPE html>', `<!DOCTYPE html>\n${BANNER.replace('{lang}', c.lang)}`);
}

// The English pair after a localized one, in parens, mirroring the on-page
// gloss. Empty on the English page.
const glossOf = (c, i) => (c.lang === 'en' || !en.shifts[i]
  ? ''
  : ` (${en.shifts[i].from} → ${en.shifts[i].to})`);

// The page as Markdown, in the order the page reads. `level` is the depth of
// the section headings (2 for the .md download and README, 3 inside llms.txt).
function pageMd(c, fmt, level) {
  const h = '#'.repeat(level);
  const L = [];
  L.push(`${h} ${fmt(c.shiftHead)}`, '');
  c.shiftIntro.forEach((x) => L.push(fmt(x), ''));
  L.push(`${h} ${fmt(c.ownHead)}`, '');
  c.shifts.forEach((s, i) => L.push(`- **${s.from} → ${s.to}**${glossOf(c, i)} — ${fmt(s.note)}`));
  L.push('', `${h} ${fmt(c.useHead)}`, '');
  c.use.forEach((x) => L.push(fmt(x), ''));
  L.push(`${h} ${fmt(c.qaHead)}`, '');
  c.qa.forEach((x) => L.push(`**${fmt(x.q)}** ${fmt(x.a)}`, ''));
  while (L[L.length - 1] === '') L.pop();
  return L.join('\n');
}

// ── sitemap.xml ───────────────────────────────────────────────────────
// Fully generated: the manifesto languages come from LANGS (so a new language
// is picked up automatically), plus the static /munich and /community entries.
function sitemap() {
  const alts = LANGS.map((l) =>
    `    <xhtml:link rel="alternate" hreflang="${l}" href="${ORIGIN}${all[l].dir}"/>`);
  alts.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${ORIGIN}${en.dir}"/>`);
  const altBlock = alts.join('\n');
  const entry = (loc, priority) =>
    `  <url>\n    <loc>${ORIGIN}${loc}</loc>\n${altBlock}\n`
    + `    <changefreq>monthly</changefreq>\n    <priority>${priority}</priority>\n  </url>`;
  const urls = LANGS.map((l) => entry(all[l].dir, l === 'en' ? '1.0' : '0.9'));
  urls.push(`  <url>\n    <loc>${ORIGIN}/munich</loc>\n`
    + `    <changefreq>weekly</changefreq>\n    <priority>0.8</priority>\n  </url>`);
  urls.push(`  <url>\n    <loc>${ORIGIN}/community</loc>\n`
    + `    <changefreq>weekly</changefreq>\n    <priority>0.8</priority>\n  </url>`);
  return `<?xml version="1.0" encoding="UTF-8"?>\n`
    + `<!-- GENERATED by manifesto/build.js — do not edit by hand. -->\n`
    + `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n`
    + `        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n`
    + `${urls.join('\n')}\n</urlset>\n`;
}

// ── llms.txt / README manifesto blocks (between markers) ──
const plain = (s) => inline(s, { emphasis: 'none', links: 'paren' });
const md = (s) => inline(s, { emphasis: 'md', links: 'md' });

// llms.txt manifesto region: English first, then every translation, so an LLM
// reading the file sees all languages. Translated pairs carry the English pair.
function llmsBlock() {
  return LANGS.map((l) => {
    const c = view(all[l]);
    return [`## Manifesto (${l === 'en' ? 'English' : c.name})`, '',
      `**Agentic Shift** — ${plain(c.hero.subtitle)}`, '', pageMd(c, plain, 3)].join('\n');
  }).join('\n\n');
}

function readmeBlock() {
  return ['> _Generated from [`manifesto/content/en.json`](manifesto/content/en.json) — edit the JSON '
    + '(and its siblings for other languages), then run `node manifesto/build.js`. Do not edit this section by hand._', '',
  `_${md(en.hero.subtitle)}_`, '', pageMd(en, md, 2)].join('\n');
}

// Standalone, downloadable Markdown of one language's page.
function downloadMd(c) {
  return ['# Agentic Shift', '', `_${md(c.hero.subtitle)}_`, '', pageMd(c, md, 2), '', '---', '',
    `${md(c.foot.by)} [Alexey Krivitsky](https://www.linkedin.com/in/alexeykrivitsky/) · ${ORIGIN}${c.dir}`, ''].join('\n');
}

// Replace the region between MANIFESTO markers; never write if markers absent.
function writeMarked(rel, block) {
  const file = path.join(ROOT, rel);
  const txt = read(file);
  const re = /<!-- MANIFESTO:START[\s\S]*?MANIFESTO:END -->/;
  if (!re.test(txt)) { console.warn(`! ${rel}: no MANIFESTO markers — skipped`); return; }
  // Short, invisible boundary markers; the human-facing "generated from …"
  // note is emitted as the first visible line of the block (a real MD link).
  const wrapped = `<!-- MANIFESTO:START -->\n\n${block}\n\n<!-- MANIFESTO:END -->`;
  const next = txt.replace(re, wrapped);
  if (next !== txt) { fs.writeFileSync(file, next); written.push(rel); }
}

// ── en → translation parity ───────────────────────────────────────────
// en.json is canonical, so anything added to it — a paragraph, a shift, a
// Q&A — must land in every translation, or the translated pages quietly keep
// serving an older manifesto. (That is exactly how the /community Q&A ran
// English-only for weeks.) This reports precisely what each language lacks and
// exits non-zero; the files are still written, so you can keep iterating while
// the translations catch up.
function parityDrift() {
  const COUNTED = ['shiftIntro', 'shifts', 'use', 'qa'];
  const NESTED = ['meta', 'hero', 'foot', 'ui'];
  const filled = (v) => typeof v === 'string' && v.trim() !== '';
  const drift = [];
  for (const lang of LANGS.filter((l) => l !== 'en')) {
    const c = all[lang];
    const gaps = [];
    Object.keys(en).filter((k) => !(k in c)).forEach((k) => gaps.push(`no "${k}"`));
    // A key present but empty serves a blank paragraph — as bad as missing.
    Object.keys(en).filter((k) => typeof en[k] === 'string' && k in c && !filled(c[k]))
      .forEach((k) => gaps.push(`empty "${k}"`));
    NESTED.forEach((n) => Object.keys(en[n] || {})
      .filter((k) => !filled((c[n] || {})[k]))
      .forEach((k) => gaps.push(`no ${n}.${k}`)));
    COUNTED.forEach((k) => {
      const want = [].concat(en[k] || []).length;
      const got = [].concat(c[k] || []).length;
      if (got !== want) gaps.push(`${k} ${got}/${want}`);
    });
    // Length alone is not parity: a shift missing its `note`, or a Q&A missing
    // its answer, renders the string "undefined" and would otherwise pass.
    [['shifts', ['from', 'to', 'note']], ['qa', ['q', 'a']]]
      .forEach(([k, fields]) => (c[k] || []).forEach((item, i) => {
        fields.filter((f) => !filled(item[f])).forEach((f) => gaps.push(`${k}[${i}].${f}`));
      }));
    ['shiftIntro', 'use'].forEach((k) => (c[k] || []).forEach((x, i) => {
      if (!filled(x)) gaps.push(`${k}[${i}]`);
    }));
    if (gaps.length) drift.push(`  ${lang}: ${gaps.join(' · ')}`);
  }
  return drift;
}

// ── write ─────────────────────────────────────────────────────────────
const written = [];

for (const lang of LANGS) {
  const c = view(all[lang]);
  // Output path comes from `dir`, not from the language code — they usually
  // match (`de` → /de/) but need not. Czech ships at /cz/ (the country code
  // people recognise) while its language code stays the ISO 639-1 `cs` used by
  // lang=/hreflang=. `dir: "/"` (en) lands at public/index.html.
  const dest = path.join(PUBLIC, c.dir.replace(/^\/+|\/+$/g, ''), 'index.html');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, render(c));
  written.push(path.relative(ROOT, dest));
  const mdDest = path.join(path.dirname(dest), `agentic-shift-${c.lang}.md`);
  fs.writeFileSync(mdDest, downloadMd(c));
  written.push(path.relative(ROOT, mdDest));
}

fs.writeFileSync(path.join(PUBLIC, 'sitemap.xml'), sitemap());
written.push('public/sitemap.xml');

writeMarked('public/llms.txt', llmsBlock());
writeMarked('README.md', readmeBlock());

console.log(`Built ${LANGS.length} language(s):\n${written.map((w) => `  ${w}`).join('\n')}`);
if (missing.length) {
  console.log(`\nNot built (no content/<lang>.json yet): ${missing.join(', ')}`);
}

const drift = parityDrift();
if (drift.length) {
  console.error(`\n✗ TRANSLATION DRIFT — en.json carries content these languages lack:\n${drift.join('\n')}\n`
    + `\n  en.json is canonical: add the missing entries to manifesto/content/<lang>.json,\n`
    + `  then rebuild. The pages above were still written — they are just incomplete.`);
  process.exitCode = 1;
} else {
  console.log(`\n✓ all ${LANGS.length - 1} translations match en.json`);
}
